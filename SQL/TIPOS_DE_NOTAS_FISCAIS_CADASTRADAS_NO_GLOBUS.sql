	CODTPDOC IN ('001', 'CTE', 'NCE', 'NDS', 'NEA', 'NEC', 'NEG', 'NES', 'NF', 'NFC', 'NFE', 'NFF', 'NFG', 'NFP', 'NFS', 'NSA', 'NSP', 'NVS')
