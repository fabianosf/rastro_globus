SELECT
	DECODE(A.CODIGOEMPRESA, 1, 'Viação Redentor Ltda', 2, 'Transportes Futuro Ltda', 3, 'Transportes Barra Ltda') EMPRESA,
	TO_CHAR(F.ENTRADASAIDANF, 'YYYY-MM-DD') "ENTRADA DA NF EM SISTEMA",
	TO_CHAR(F.ENTRADASAIDANF, 'YYYY-MM') "ANO-MÊS",
	C.CODIGOGRE CODIGO_GRUPO_ESTOQUE,
	H.DESCRICAOGRE DESCRICAO_GRUPO_ESTOQUE,
	C.CODIGOINTERNOMATERIAL "CÓDIGO DO MATERIAL",
	C.CODIGOINTERNOMATERIAL || C.DESCRICAOMAT "CÓD. E NOME DO MATERIAL",
	ROUND(D.VALORUNITARIOITENSNF, 2) "VALOR UNITÁRIO DO MATERIAL"
FROM
	(SELECT CODIGOEMPRESA, DATAMOVTO, SEQMOVTO, CODINTFUNC, CODINTNF, CODIGOHISMOV FROM GLOBUS.EST_MOVTO WHERE (DATAMOVTO BETWEEN TO_DATE('01/01/2015', 'dd/MM/yyyy') AND TO_DATE('30/06/2025', 'dd/MM/yyyy')) AND CODIGOHISMOV IN ('1', '10') AND CODIGOEMPRESA IN (1, 2, 3)) A
	LEFT OUTER JOIN (SELECT SEQMOVTO, CODIGOMATINT, NROPLANOCTCREDITO, CODCONTACTBCREDITO, NROPLANOCTDEBITO, CODCONTACTBDEBITO, QTDEITENSMOVTO, VALORTOTALITENSMOVTO FROM GLOBUS.EST_ITENSMOVTO) B ON (A.SEQMOVTO = B.SEQMOVTO)
	LEFT OUTER JOIN (SELECT DESCRICAOMAT, CODIGOMATINT, CODIGOGRC, CODIGOGRE, CODIGOINTERNOMATERIAL FROM GLOBUS.EST_CADMATERIAL WHERE CODIGOGRE = 01) C ON (B.CODIGOMATINT = C.CODIGOMATINT)
	LEFT OUTER JOIN (SELECT CODIGOFORN, CODINTNF, NUMERONF, SERIENF, CODTPDOC, DATAEMISSAONF, ENTRADASAIDANF, DATALANCTO, NATUREZAOPERACAONF, VALORTOTALNF FROM GLOBUS.BGM_NOTAFISCAL) F ON (A.CODINTNF = F.CODINTNF)
	LEFT OUTER JOIN (SELECT VALORUNITARIOITENSNF, CODINTNF FROM EST_ITENSNF GROUP BY VALORUNITARIOITENSNF, CODINTNF) D  ON (F.CODINTNF = D.CODINTNF)
	LEFT OUTER JOIN (SELECT CODIGOFORN, NRFORN, NFANTASIAFORN FROM GLOBUS.BGM_FORNECEDOR) E ON (F.CODIGOFORN = E.CODIGOFORN)
	LEFT OUTER JOIN (SELECT CODIGOGRC, DESCRICAOGRC FROM EST_GRUPOCOMPRAS) G ON (G.CODIGOGRC = C.CODIGOGRC)
	LEFT OUTER JOIN (SELECT CODIGOGRE, DESCRICAOGRE FROM EST_GRUPOESTOQUE) H ON (H.CODIGOGRE = C.CODIGOGRE)
WHERE
	A.DATAMOVTO BETWEEN TO_DATE('01/01/2015', 'dd/MM/yyyy') AND TO_DATE('30/06/2025', 'dd/MM/yyyy')
	AND A.CODIGOHISMOV IN ('1', '10')
	AND A.CODIGOEMPRESA IN (1, 2, 3)
	AND C.CODIGOGRE = 01
ORDER BY
	1,
	6,
	2


